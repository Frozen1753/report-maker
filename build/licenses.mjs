// Writes THIRD-PARTY-LICENSES.txt: the license files of the packages a built
// report embeds, read from node_modules (run `npm install` first).
//
//   npm run licenses          write the file
//   npm run licenses:check    exit 1 if the file is out of date (for CI)
//
// "Production" = every package of package-lock.json that is not dev-only.
// Output is deterministic (no date, sorted): the file only changes when the
// dependencies do.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = path.join(root, "THIRD-PARTY-LICENSES.txt");
const CHECK = process.argv.includes("--check");

/** Type-only packages: nothing of them is in a built report. Remove a line to list them anyway. */
const EXCLUDE = [/^@types\//, /^csstype$/];

/** LICENSE, LICENSE.md, LICENCE, LICENSE-MIT, COPYING, NOTICE... */
const LICENSE_FILE = /^(licen[cs]e|copying|notice)([._-].*)?$/i;

const BAR = "=".repeat(78);

const HEADER = `THIRD-PARTY LICENSES
====================

Report Maker is released under the MIT License (see LICENSE).

A built report embeds the following third-party packages. Each one is
distributed under the license and copyright notice reproduced below.

Build tools (Vite, MDX, Shiki, Mermaid, puppeteer-core, ...) are development
dependencies: they are installed by \`npm install\` and are not part of a built
report, so they are not listed here. Neither are type-only packages (@types/*,
csstype), which ship no code.

This file is generated by build/licenses.mjs (\`npm run licenses\`).
`;

let problems = 0;
const warn = (message) => {
    problems++;
    console.warn(`[licenses] ${message}`);
};

const lockFile = path.join(root, "package-lock.json");
if (!fs.existsSync(lockFile)) {
    console.error("[licenses] package-lock.json not found: run `npm install` first.");
    process.exit(1);
}
const lock = JSON.parse(fs.readFileSync(lockFile, "utf-8"));

/** Name of the package installed at "node_modules/a/node_modules/@scope/b" -> "@scope/b". */
const nameOf = (key, meta) => meta.name ?? key.slice(key.lastIndexOf("node_modules/") + "node_modules/".length);

const licenseOf = (pkg) => {
    if (typeof pkg.license === "string") return pkg.license;
    if (pkg.license?.type) return pkg.license.type;
    if (Array.isArray(pkg.licenses)) return pkg.licenses.map((l) => l.type).join(" OR ");
    return "UNKNOWN";
};

// text -> packages sharing exactly that text
const groups = new Map();
const seen = new Set();

for (const [key, meta] of Object.entries(lock.packages ?? {})) {
    if (key === "" || meta.dev || meta.link) continue;

    const name = nameOf(key, meta);
    if (EXCLUDE.some((pattern) => pattern.test(name))) continue;

    const dir = path.join(root, key);
    if (!fs.existsSync(path.join(dir, "package.json"))) {
        warn(`${name}: ${key} is not installed (run \`npm install\`).`);
        continue;
    }
    const pkg = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf-8"));
    const id = `${name}@${pkg.version}`;
    if (seen.has(id)) continue;
    seen.add(id);

    const files = fs
        .readdirSync(dir)
        .filter((file) => LICENSE_FILE.test(file) && fs.statSync(path.join(dir, file)).isFile())
        .sort();
    if (files.length === 0) {
        warn(`${id}: no LICENSE file found in ${key} (declared license: ${licenseOf(pkg)}). Add its text by hand.`);
        continue;
    }

    const text = files
        .map((file) => {
            const content = fs.readFileSync(path.join(dir, file), "utf-8").replace(/\r\n/g, "\n").trim();
            return files.length > 1 ? `[${file}]\n\n${content}` : content;
        })
        .join("\n\n");

    const members = groups.get(text) ?? [];
    members.push({ name, version: pkg.version, license: licenseOf(pkg) });
    groups.set(text, members);
}

const sections = [...groups]
    .map(([text, members]) => ({ text, members: members.sort((a, b) => a.name.localeCompare(b.name)) }))
    .sort((a, b) => a.members[0].name.localeCompare(b.members[0].name))
    .map(({ text, members }) => {
        const list = members.map((m) => `  - ${m.name} ${m.version} (${m.license})`).join("\n");
        return `${BAR}\nPackages:\n${list}\n${BAR}\n\n${text}\n`;
    });

const output = `${HEADER}\n${sections.join("\n")}`;
const count = [...groups.values()].reduce((n, members) => n + members.length, 0);

if (CHECK) {
    const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, "utf-8").replace(/\r\n/g, "\n") : "";
    if (current !== output || problems > 0) {
        console.error("[licenses] THIRD-PARTY-LICENSES.txt is out of date: run `npm run licenses`.");
        process.exit(1);
    }
    console.log(`[licenses] up to date (${count} package(s)).`);
} else {
    fs.writeFileSync(OUTPUT, output);
    console.log(`[licenses] ${count} package(s) in ${groups.size} license text(s) -> THIRD-PARTY-LICENSES.txt`);
    if (problems > 0) process.exitCode = 1;
}