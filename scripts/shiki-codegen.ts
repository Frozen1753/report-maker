import fs from 'node:fs'
import path from 'node:path'
import postcss from 'postcss'
import { bundledLanguagesInfo, bundledThemesInfo } from 'shiki'

// Shiki special-cases these — no grammar import needed, never fails.
const BUILTIN_NO_IMPORT = new Set(['text', 'plaintext', 'txt', 'ansi'])

const SHIKI_LIGHT_VAR = '--code-theme-light'
const SHIKI_DARK_VAR = '--code-theme-dark'
const DEFAULT_SHIKI_LIGHT = 'github-light'
const DEFAULT_SHIKI_DARK = 'github-dark'

const LANG_RE = /<Code\b[\s\S]*?\blang=(?:"([^"]+)"|'([^']+)'|\{["']([^"']+)["']\})[\s\S]*?>/g

function detectLanguages(mdxSource: string): string[] {
  const found = new Set<string>()
  for (const m of mdxSource.matchAll(LANG_RE)) {
    const lang = m[1] ?? m[2] ?? m[3]
    if (lang) found.add(lang)
  }
  return [...found]
}

function readThemePair(cssSource: string): { light: string; dark: string } {
  const root = postcss.parse(cssSource)
  let light = DEFAULT_SHIKI_LIGHT
  let dark = DEFAULT_SHIKI_DARK
  root.walkDecls((decl) => {
    if (decl.prop === SHIKI_LIGHT_VAR) light = decl.value.trim()
    if (decl.prop === SHIKI_DARK_VAR) dark = decl.value.trim()
  })
  return { light, dark }
}

export interface GenerateOptions {
  reportMdxPath: string
  styleCssPath: string
  outPath: string
}

export function generateShikiBundle({ reportMdxPath, styleCssPath, outPath }: GenerateOptions): void {
  const mdx = fs.readFileSync(reportMdxPath, 'utf-8')
  const css = fs.existsSync(styleCssPath) ? fs.readFileSync(styleCssPath, 'utf-8') : ''

  const detected = detectLanguages(mdx)
  const validLangIds = new Set(bundledLanguagesInfo.flatMap((l) => [l.id, ...(l.aliases ?? [])]))
  const validThemeIds = new Set(bundledThemesInfo.map((t) => t.id))

  const langsToImport: string[] = []
  for (const lang of detected) {
    if (BUILTIN_NO_IMPORT.has(lang)) continue
    if (!validLangIds.has(lang)) {
      console.warn(
        `[shiki-codegen] ⚠ "${lang}" used as a <Code lang="${lang}"> isn't a known Shiki language or alias — it will render unhighlighted. Typo?`,
      )
      continue
    }
    langsToImport.push(lang)
  }

  let { light: lightTheme, dark: darkTheme } = readThemePair(css)
  for (const [label, id] of [
    ['light', lightTheme],
    ['dark', darkTheme],
  ] as const) {
    if (!validThemeIds.has(id)) {
      console.warn(`[shiki-codegen] ⚠ "${id}" (${label} code theme) isn't a known Shiki theme — falling back to default.`)
      if (label === 'light') lightTheme = DEFAULT_SHIKI_LIGHT
      else darkTheme = DEFAULT_SHIKI_DARK
    }
  }

  const langImportLines = langsToImport.map((lang, i) => `import lang_${i} from 'shiki/langs/${lang}.mjs'`)
  const langVarNames = langsToImport.map((_, i) => `lang_${i}`)

  const out = `// AUTO-GENERATED by scripts/shiki-codegen.ts — do not edit by hand.
// Regenerated on every build from report.mdx (languages actually used)
// and style.css (--code-theme-light / --code-theme-dark).
import { createHighlighterCore } from 'shiki/core'
import { createOnigurumaEngine } from 'shiki/engine/oniguruma'
${langImportLines.join('\n')}
import themeLight from 'shiki/themes/${lightTheme}.mjs'
import themeDark from 'shiki/themes/${darkTheme}.mjs'

export const highlighterPromise = createHighlighterCore({
  langs: [${langVarNames.join(', ')}],
  themes: [themeLight, themeDark],
  engine: createOnigurumaEngine(() => import('shiki/wasm')),
})
`

  fs.mkdirSync(path.dirname(outPath), { recursive: true })
  fs.writeFileSync(outPath, out)

  console.log(
    `[shiki-codegen] bundled ${langsToImport.length} language(s) (${langsToImport.join(', ') || 'none'}) + 2 themes (${lightTheme}, ${darkTheme})`,
  )
}
